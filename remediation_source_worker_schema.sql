create or replace function market_governance.remediation_store_source_v1(p_batch_id bigint,p_source jsonb)
returns uuid language plpgsql security invoker set search_path=pg_catalog as $$
declare sid uuid; packed bytea; h bytea; existing market_governance.remediation_source_response_v1%rowtype;
begin
 sid=(p_source->>'source_id')::uuid;
 if sid is null then raise exception 'source_id_required'; end if;
 packed=decode(p_source->>'compressed_base64','base64');
 h=sha256(packed);
 if encode(h,'hex')<>p_source->>'compressed_sha256' then raise exception 'compressed_source_sha_mismatch'; end if;
 if exists(select 1 from jsonb_object_keys(coalesce(p_source->'headers','{}'::jsonb)) k where lower(k) in ('authorization','apikey','api-key','cookie','set-cookie','x-astra-token')) then
  raise exception 'sensitive_source_header_rejected';
 end if;
 insert into market_governance.remediation_source_response_v1(
 source_id,batch_id,role,source_url,http_status,response_headers,received_at,revision_at,
 source_sha256,stored_body_sha256,compressed_sha256,original_bytes,compressed_body,storage_encoding,parser_version,credential_redactions,provenance)
 values(sid,p_batch_id,p_source->>'role',p_source->>'source_url',(p_source->>'http_status')::integer,
 coalesce(p_source->'headers','{}'::jsonb),(p_source->>'received_at')::timestamptz,nullif(p_source->>'revision_at','')::timestamptz,
 decode(p_source->>'source_sha256','hex'),decode(p_source->>'stored_body_sha256','hex'),h,(p_source->>'original_bytes')::bigint,packed,'gzip',
 p_source->>'parser_version',coalesce((p_source->>'credential_redactions')::integer,0),coalesce(p_source->'provenance','{}'::jsonb))
 on conflict(source_id) do nothing;
 select * into strict existing from market_governance.remediation_source_response_v1 where source_id=sid;
 if existing.batch_id<>p_batch_id or existing.compressed_sha256<>h then raise exception 'source_version_conflict'; end if;
 return sid;
end $$;

