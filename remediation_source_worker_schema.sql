create or replace function market_governance.remediation_depth_bands_valid_v1(p_bands jsonb)
returns boolean language plpgsql immutable security invoker set search_path=pg_catalog as $$
declare i integer; item jsonb; expected integer; quantity numeric; notional numeric; prior_quantity numeric; prior_notional numeric;
begin
 if p_bands is null then return true; end if;
 if jsonb_typeof(p_bands)<>'array' or jsonb_array_length(p_bands)<>10 then return false; end if;
 for i in 1..10 loop
  item=p_bands->(i-1); expected=case when i<=5 then i-6 else i-5 end;
  if jsonb_typeof(item)<>'array' or jsonb_array_length(item)<>3 or (item->>0)::numeric is distinct from expected::numeric then return false; end if;
  if length(item->>1)>120 or length(item->>2)>120 or
   item->>1 !~ '^[+]?[0-9]+([.][0-9]+)?([eE][-+]?[0-9]+)?$' or
   item->>2 !~ '^[+]?[0-9]+([.][0-9]+)?([eE][-+]?[0-9]+)?$' then return false; end if;
  quantity=(item->>1)::numeric; notional=(item->>2)::numeric;
  if quantity is null or notional is null or (quantity=0)<>(notional=0) then return false; end if;
  if i between 2 and 5 and (quantity>prior_quantity or notional>prior_notional) then return false; end if;
  if i between 7 and 10 and (quantity<prior_quantity or notional<prior_notional) then return false; end if;
  prior_quantity=quantity; prior_notional=notional;
 end loop;
 return true;
exception when others then return false;
end $$;

