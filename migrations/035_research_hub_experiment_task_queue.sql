-- Durable atomic task queue for resumable research enumeration.
create table if not exists research_hub.experiment_tasks (
  task_id bigint generated by default as identity primary key,
  run_id uuid not null references research_hub.experiment_runs(run_id) on delete cascade,
  task_key text not null,
  task_type text not null default 'feature_screen',
  payload jsonb not null default '{}'::jsonb,
  status text not null default 'queued' check(status in ('queued','running','completed','failed','cancelled')),
  priority integer not null default 100,
  attempts integer not null default 0,
  claimed_by text,
  heartbeat_at timestamptz,
  last_error text,
  result_summary jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  started_at timestamptz,
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  unique(run_id,task_key)
);
create index if not exists idx_experiment_tasks_claim on research_hub.experiment_tasks(status,priority,task_id);
create index if not exists idx_experiment_tasks_run on research_hub.experiment_tasks(run_id,status);

create or replace function research_hub.claim_experiment_task(p_worker_id text)
returns research_hub.experiment_tasks language plpgsql set search_path=research_hub,pg_temp as $$
declare claimed research_hub.experiment_tasks%rowtype;
begin
 with next_task as (
   select task_id from research_hub.experiment_tasks where status='queued'
   order by priority,task_id for update skip locked limit 1
 )
 update research_hub.experiment_tasks t
 set status='running',claimed_by=p_worker_id,attempts=t.attempts+1,
     started_at=coalesce(t.started_at,now()),heartbeat_at=now(),updated_at=now()
 from next_task n where t.task_id=n.task_id returning t.* into claimed;
 return claimed;
end $$;

create or replace function research_hub.heartbeat_experiment_task(p_task_id bigint,p_worker_id text)
returns boolean language sql set search_path=research_hub,pg_temp as $$
with u as (
 update research_hub.experiment_tasks set heartbeat_at=now(),updated_at=now()
 where task_id=p_task_id and status='running' and claimed_by=p_worker_id returning 1
) select exists(select 1 from u)
$$;

create or replace function research_hub.complete_experiment_task(p_task_id bigint,p_worker_id text,p_result_summary jsonb default '{}'::jsonb)
returns boolean language sql set search_path=research_hub,pg_temp as $$
with u as (
 update research_hub.experiment_tasks
 set status='completed',result_summary=coalesce(p_result_summary,'{}'::jsonb),completed_at=now(),heartbeat_at=now(),updated_at=now()
 where task_id=p_task_id and status='running' and claimed_by=p_worker_id returning 1
) select exists(select 1 from u)
$$;

create or replace function research_hub.fail_experiment_task(p_task_id bigint,p_worker_id text,p_error text,p_retry boolean default true)
returns boolean language sql set search_path=research_hub,pg_temp as $$
with u as (
 update research_hub.experiment_tasks
 set status=case when p_retry then 'queued' else 'failed' end,
     claimed_by=case when p_retry then null else claimed_by end,
     heartbeat_at=case when p_retry then null else now() end,
     last_error=left(p_error,4000),completed_at=case when p_retry then null else now() end,updated_at=now()
 where task_id=p_task_id and status='running' and claimed_by=p_worker_id returning 1
) select exists(select 1 from u)
$$;

create or replace function research_hub.reclaim_stale_experiment_tasks(p_stale_after interval default interval '10 minutes')
returns bigint language plpgsql set search_path=research_hub,pg_temp as $$
declare n bigint;
begin
 update research_hub.experiment_tasks
 set status='queued',claimed_by=null,heartbeat_at=null,
     last_error=coalesce(last_error,'')||case when last_error is null or last_error='' then '' else E'\n' end||'Reclaimed after stale worker heartbeat',updated_at=now()
 where status='running' and heartbeat_at<now()-p_stale_after;
 get diagnostics n=row_count;
 return n;
end $$;
